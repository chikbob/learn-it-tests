const difficulties = ['surface', 'understanding', 'understanding', 'trick']

function rotateOptions(options, correctValue, shift) {
  const rotated = options.map((_, index) => options[(index + shift) % options.length])
  return { options: rotated, correct: rotated.indexOf(correctValue) }
}

function slug(value) {
  return value.toLocaleLowerCase('ru').replaceAll('ё', 'е').replace(/[^\p{L}\p{N}]+/gu, '-').replace(/^-|-$/g, '')
}

export const conceptQuestions = []
let nextId = 1000

Object.entries(concepts).forEach(([section, entries]) => {
  entries.forEach(([term, definition], conceptIndex) => {
    const distractors = [1, 2, 3].map(offset => entries[(conceptIndex + offset) % entries.length])
    const family = `${section}:concept:${slug(term)}`
    const definitionSet = rotateOptions([definition, ...distractors.map(item => item[1])], definition, conceptIndex % 4)
    const termSet = rotateOptions([term, ...distractors.map(item => item[0])], term, (conceptIndex + 1) % 4)
    const pair = `${term} — ${definition}`
    const pairSet = rotateOptions([pair, ...distractors.map(item => `${term} — ${item[1]}`)], pair, (conceptIndex + 2) % 4)
    const falseSet = rotateOptions([definition, ...distractors.map(item => item[1])], definition, (conceptIndex + 3) % 4)

    conceptQuestions.push(
      { id: nextId++, section, difficulty: difficulties[0], family, text: `Что обозначает термин «${term}»?`, options: definitionSet.options, correct: definitionSet.correct, explanation: `${term} — ${definition}.`, code: '' },
      { id: nextId++, section, difficulty: difficulties[1], family, text: `Какому термину соответствует определение: «${definition}»?`, options: termSet.options, correct: termSet.correct, explanation: `Это определение термина «${term}».`, code: '' },
      { id: nextId++, section, difficulty: difficulties[2], family, text: `Какое утверждение о понятии «${term}» является верным?`, options: falseSet.options, correct: falseSet.correct, explanation: `Верное свойство: ${definition}.`, code: '' },
      { id: nextId++, section, difficulty: difficulties[3], family, text: `Выберите корректную пару «термин — определение» для понятия «${term}».`, options: pairSet.options, correct: pairSet.correct, explanation: `Корректная пара: ${pair}.`, code: '' },
    )
  })
})
